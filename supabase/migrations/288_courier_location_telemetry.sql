BEGIN;
ALTER TABLE public.deliveries
  ADD COLUMN IF NOT EXISTS current_speed_mps numeric,
  ADD COLUMN IF NOT EXISTS current_heading_degrees numeric,
  ADD COLUMN IF NOT EXISTS current_accuracy_meters numeric,
  ADD COLUMN IF NOT EXISTS courier_battery_percent integer,
  ADD COLUMN IF NOT EXISTS location_recorded_at timestamptz;
CREATE TABLE IF NOT EXISTS public.courier_location_samples (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  courier_id uuid,
  latitude double precision NOT NULL,
  longitude double precision NOT NULL,
  speed_mps numeric,
  heading_degrees numeric,
  accuracy_meters numeric,
  battery_percent integer,
  recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_courier_location_samples_order_time
  ON public.courier_location_samples(order_id, recorded_at DESC);
ALTER TABLE public.courier_location_samples ENABLE ROW LEVEL SECURITY;
CREATE POLICY courier_location_samples_order_participants
ON public.courier_location_samples FOR SELECT TO authenticated
USING (
  courier_id = auth.uid()
  OR EXISTS (
    SELECT 1 FROM public.orders o
    LEFT JOIN public.restaurants r ON r.id = o.restaurant_id
    WHERE o.id = order_id
      AND (COALESCE(o.client_id, o.customer_id) = auth.uid()
        OR r.owner_id = auth.uid()
        OR public.is_admin())
  )
);
CREATE OR REPLACE FUNCTION public.capture_courier_location_sample()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_courier_id uuid;
BEGIN
  IF NEW.current_latitude IS NULL OR NEW.current_longitude IS NULL THEN
    RETURN NEW;
  END IF;
  IF OLD.location_recorded_at IS NOT DISTINCT FROM NEW.location_recorded_at THEN
    RETURN NEW;
  END IF;
  SELECT courier_id INTO v_courier_id FROM orders WHERE id = NEW.order_id;
  INSERT INTO courier_location_samples (
    order_id, courier_id, latitude, longitude, speed_mps,
    heading_degrees, accuracy_meters, battery_percent, recorded_at
  ) VALUES (
    NEW.order_id, v_courier_id, NEW.current_latitude, NEW.current_longitude,
    NEW.current_speed_mps, NEW.current_heading_degrees,
    NEW.current_accuracy_meters, NEW.courier_battery_percent,
    COALESCE(NEW.location_recorded_at, now())
  );
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_capture_courier_location_sample ON public.deliveries;
CREATE TRIGGER trg_capture_courier_location_sample
AFTER UPDATE OF current_latitude, current_longitude, location_recorded_at
ON public.deliveries FOR EACH ROW
EXECUTE FUNCTION public.capture_courier_location_sample();
DO $$
BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.courier_location_samples;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
COMMIT;
